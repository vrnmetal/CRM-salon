"""
Движок подсказок: hints-first (близнец permission-first).

Правило проекта: каждый неочевидный управляющий элемент регистрирует здесь свою
подсказку ОДНОВРЕМЕННО с кодом элемента. Подсказки всплывают при наведении/долгом
тапе; показ управляется тумблером в профиле пользователя (User.show_hints).

Единый реестр текстов — чтобы подсказки не были размазаны по шаблонам и их легко
было вычитать/поправить тон.
"""

# Единый реестр подсказок: ключ -> текст
REGISTRY: dict[str, str] = {}


def register_hint(key: str, text: str) -> str:
    if key in REGISTRY:
        raise ValueError(f"Подсказка уже зарегистрирована: {key}")
    REGISTRY[key] = text
    return key


def get_hint(key: str) -> str:
    return REGISTRY.get(key, "")


